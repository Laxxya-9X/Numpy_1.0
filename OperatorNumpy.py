import numpy as np


a = np.array([1,2,3])
b = np.array([5,6,7])

#addition
print(a+b)

#subtraction
print(b-a)

#multiplication
print(a*b)

# division
print(a/b)

#floor division
print(b//a)

#power
print(b**a)

#sum
print(np.sum(a))

#mean
print(np.mean(a))

#variance
print(np.var(a))

#standard deviation
print(np.std(a))

#Universal Function --- SquareRoot, Exponential
print(np.square(a))

print(np.sqrt(a))

print(np.exp(a))

#Aggregation funciton  ------ sum , min, max , SD, Var

print(np.min(a))

print(np.max(a))

